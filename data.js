function formatKoreanPrice(val) {
  if (!val) return '0원';
  const eok = Math.floor(val / 10000);
  const man = val % 10000;
  if (eok > 0 && man > 0) {
    return `${eok}억 ${man.toLocaleString()}만원`;
  } else if (eok > 0) {
    return `${eok}억원`;
  } else {
    return `${man.toLocaleString()}만원`;
  }
}

